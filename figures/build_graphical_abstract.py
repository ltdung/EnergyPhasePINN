def draw_curve(s, x, measured, predicted):
    x0, y0, pw, ph = 1140, 543, 388, 245
    max_force = 150
    px = lambda values: x0 + np.asarray(values) * pw
    py = lambda values: y0 - np.asarray(values) / max_force * ph
    s.circle(1150, 254, 4.5, MUTED)
    s.text(1166, 262, "MD", size=23)
    s.line(1284, 254, 1320, 254, BLUE, 3.5)
    s.text(1331, 262, "Prediction", size=23)
    s.text(1107, 291, "Force (nN)", size=23, fill=MUTED)
    for tick in (0, 50, 100, 150):
        y = float(py(tick))
        s.line(x0, y, x0 + pw, y, BORDER, 1.2)
        s.text(x0 - 13, y + 7, str(tick), size=22, fill=MUTED, anchor="end")
    for tick in (0, 0.5, 1):
        xt = float(px(tick))
        s.line(xt, y0, xt, y0 + 7, INK, 1.5)
        s.text(xt, y0 + 32, f"{tick:g}", size=22, fill=MUTED, anchor="middle")
    s.line(x0, y0 - ph, x0, y0, INK, 1.6)
    s.line(x0, y0, x0 + pw, y0, INK, 1.6)
    s.add('<g clip-path="url(#plot-clip)">')
    for xp, yp in zip(px(x), py(measured)):
        s.circle(f"{xp:.3f}", f"{yp:.3f}", 2.3, "#99A7B0")
    points = " ".join(f"{xp:.3f},{yp:.3f}" for xp, yp in zip(px(x), py(predicted)))
    s.add(f'<polyline points="{points}" fill="none" stroke="{BLUE}" '
          'stroke-width="3.8" stroke-linejoin="round" stroke-linecap="round"/>')
    s.add("</g>")
    s.text(x0 + pw / 2, 616, f'Normalized depth  δ / δ{sub("max")}',
           size=24, anchor="middle", raw=True)
    s.text(x0 + pw / 2, 650, "Held-out curve · fold 0, seed 0", size=22,
           fill=MUTED, anchor="middle")


