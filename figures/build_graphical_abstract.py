class SVG:
    def __init__(self):
        self.parts = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="183mm" '
            f'height="{183 * H / W:.5f}mm" viewBox="0 0 {W} {H}" '
            'font-family="Arial, Helvetica, sans-serif" role="img" '
            'aria-labelledby="figure-title figure-description">',
            '<title id="figure-title">Energy-based learning of nanoindentation</title>',
            '<desc id="figure-description">AlCuNiTiZr high-entropy-alloy molecular-dynamics '
            'loading data feed elastic, plastic and hardening energy branches with smooth '
            'depth-dependent regime weights and a learned residual energy. The predicted force '
            'is the full depth derivative of their scalar loading potential. The right-hand '
            'plot shows the actual held-out curve for LOCO fold 0, seed 0: 557 corrected '
            'loading points, grain size 4.0696, temperature 300, velocity 25 in the source CSV. '
            'Depth is normalized by the maximum held-out loading depth. Overall results '
            'across 18 folds and 5 seeds are R squared 0.957 plus or minus 0.040 and '
            'mean absolute error 7.07 nN. The nanoindentation drawing is schematic.</desc>',
            '<metadata>Sources: revision_models.py; revision_data.py; '
            'generate_figure_data.py; Indent_AlCuNiTiZr.csv; '
            'results/figure_data/fig1_loading_branch.npz (y_true_new, y_pred_new); '
            'response_tables/Table1_model_comparison_full_budget.csv. '
            'Plot provenance: EnergyPhasePINN, corrected time-ordered loading extraction, '
            'LOCO fold 0, seed 0, epochs=800. All 557 observations and predictions retained. '
            'Prediction polyline connects saved values in original loading order; no '
            'smoothing or fitted display curve. Input depth units are intentionally '
            'avoided by plotting delta/delta_max. Regime names denote model components, '
            'not measured microstructural phase fractions. R squared uncertainty is the '
            'standard deviation across 90 fold/seed runs. Figure generated by '
            'paper_figures/build_graphical_abstract.py.</metadata>',
            '<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" '
            'markerWidth="7" markerHeight="7" orient="auto-start-reverse">'
            f'<path d="M 0 0 L 10 5 L 0 10 z" fill="{INK}"/></marker>'
            '<clipPath id="plot-clip"><rect x="1140" y="298" width="388" '
            'height="245"/></clipPath>'
            '<clipPath id="alloy-clip"><path d="M 86 373 H 174 '
            'Q 246 411 318 373 H 412 V 490 H 86 Z"/></clipPath></defs>',
        ]
        self.rect(0, 0, W, H, "#FFFFFF")

    def add(self, value):
        self.parts.append(value)

    def text(self, x, y, label, size=24, fill=INK, weight=400,
             anchor="start", raw=False, **attrs):
        extra = " ".join(f'{k.replace("_", "-")}="{v}"' for k, v in attrs.items())
        label = label if raw else html.escape(str(label))
        self.add(f'<text x="{x}" y="{y}" font-size="{size}" fill="{fill}" '
                 f'font-weight="{weight}" text-anchor="{anchor}" {extra}>{label}</text>')

    def rect(self, x, y, w, h, fill, stroke="none", r=0, sw=1.5):
        self.add(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" '
                 f'rx="{r}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>')

    def line(self, x1, y1, x2, y2, color=BORDER, sw=2, arrow=False, dash=None):
        attrs = ' marker-end="url(#arrow)"' if arrow else ""
        if dash:
            attrs += f' stroke-dasharray="{dash}"'
        self.add(f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" '
                 f'stroke="{color}" stroke-width="{sw}"{attrs}/>')

    def path(self, d, stroke=INK, sw=2, fill="none", **attrs):
        extra = " ".join(f'{k.replace("_", "-")}="{v}"' for k, v in attrs.items())
        self.add(f'<path d="{d}" fill="{fill}" stroke="{stroke}" '
                 f'stroke-width="{sw}" stroke-linejoin="round" '
                 f'stroke-linecap="round" {extra}/>')

    def circle(self, x, y, r, fill, stroke="none", sw=1):
        self.add(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{fill}" '
                 f'stroke="{stroke}" stroke-width="{sw}"/>')

    def write(self, path):
        content = "\n".join(self.parts + ["</svg>"]) + "\n"
        ET.fromstring(content)
        path.write_text(content, encoding="utf-8")


def sub(label):
    return f'<tspan baseline-shift="sub" font-size="70%">{label}</tspan>'


def sup(label):
    return f'<tspan baseline-shift="super" font-size="70%">{label}</tspan>'


def source_curve():
    loading = data.keep_loading(data.load())
    heldout = loading.loc[data.group_id(loading) == 0]
    arrays = np.load(ROOT / "results/figure_data/fig1_loading_branch.npz")
    measured = heldout["Force"].to_numpy()
    # Verify both length and row alignment, rather than assuming the saved force
    # values belong to this particular curve or to a depth-sorted version.
    np.testing.assert_allclose(arrays["y_true_new"], measured, rtol=2e-6, atol=1e-5)
    assert len(heldout) == len(arrays["y_pred_new"]) == 557
    depth = heldout["Depth"].to_numpy()
    assert np.all(np.diff(depth) >= 0)
    assert data.check_time_ordering(data.load()) == []
    assert (ROOT / "response_tables/Table1_model_comparison_full_budget.csv").is_file()
    for values in (arrays["y_true_new"], arrays["y_pred_new"]):
        assert np.isfinite(values).all()
        assert values.min() >= 0 and values.max() <= 150, "Plot limits would clip data"
    return depth / depth.max(), arrays["y_true_new"], arrays["y_pred_new"]


